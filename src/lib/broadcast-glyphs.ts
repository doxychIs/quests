export function hashString(text:string){let n=2166136261;for(const c of text)n=Math.imul(n^c.charCodeAt(0),16777619);return n>>>0}
export function randomUnit(seed:number){let n=seed|0;n=Math.imul(n^(n>>>16),0x21f0aaad);n=Math.imul(n^(n>>>15),0x735a2d97);return((n^(n>>>15))>>>0)/4294967296}
const paths=new Map<string,string>();
export function glyphId(char:string){const key=glyphRows[char.toUpperCase()]?char.toUpperCase():'?';return'broadcast-glyph-'+key.charCodeAt(0).toString(16)}
export function glyphPath(char:string){
 const key=char.toUpperCase();if(paths.has(key))return paths.get(key)!;
 const rows=glyphRows[key]||glyphRows['?'];let d='';
 rows.forEach((row,y)=>{let x=0;while(x<row.length){if(row[x]!=='1'){x++;continue}const start=x;while(row[x]==='1')x++;const width=x-start;
  // Contours have tiny clipped corners rather than perfectly clean square pixels.
  d+=`M${start+.07} ${y}h${width-.14}l.07 .12v.77l-.1 .11h${-width+.2}l-.04 -.12v-.76Z`;
 }});paths.set(key,d);return d;
}
export function glyphObject(char:string,index:number,message:string,seed=0){
 const h=hashString(message+':'+index+':'+seed),edit=letterEdits[message.toUpperCase()]?.[index]||{};
 return{char,index,path:edit.path||glyphPath(char),customPath:edit.path,color:edit.color,weight:edit.weight??(randomUnit(h+31)*.045),scaleY:edit.scaleY??1,dx:edit.dx??(randomUnit(h)-.5)*.12,dy:edit.dy??(randomUnit(h+11)-.5)*.18,rotate:edit.rotate??(randomUnit(h+19)-.5)*1.1,scaleX:edit.scaleX??(.96+randomUnit(h+29)*.055),opacity:edit.opacity??(.78+randomUnit(h+41)*.2),
  // These holes are sub-pixel at body size and visible nicks at title size.
  damage:edit.damage??`M${(.7+randomUnit(h+61)*3).toFixed(2)} ${(1+randomUnit(h+73)*4.7).toFixed(2)}h.68v.13h-.68Z`,
  scratch:`M${(.5+randomUnit(h+89)*3.5).toFixed(2)} .4l-.12 5.8`,seed:h};
}
export const glyphAdvance=6.2,glyphEm=9;
const canvasPaths=new Map<string,Path2D>();
const canvasPath=(d:string)=>{let path=canvasPaths.get(d);if(!path){path=new Path2D(d);canvasPaths.set(d,path)}return path};
export function graphicWords(text:string,seed=0){let index=0;return text.split(/(\s+)/).filter(Boolean).map(word=>{
 if(/^\s+$/.test(word)){index+=word.length;return{space:true,text:word,width:3.2,letters:[]}}
 const start=index;const letters=[...word].map(char=>glyphObject(char,index++,text,seed));
 return{space:false,text:word,start,width:letters.length*glyphAdvance-.7,letters};
})}
/** Draw editable vector assets into the source image BEFORE the analog signal pass. */
export function drawGraphicText(ctx:CanvasRenderingContext2D,text:string,x:number,y:number,size:number,color:string,seed=0,maxWidth=Infinity,reveal?:{count:number;caret:boolean}){
 const scale=size/glyphEm;let px=x,py=y,emitted=0,cursorX=x,cursorY=y;
 for(const word of graphicWords(text,seed)){
  if(word.space){px+=3.2*scale;continue}
  if(px>x&&px+word.width*scale>x+maxWidth){px=x;py+=size*1.55}
  for(const [n,g]of word.letters.entries()){
   if(reveal&&emitted++>=reveal.count)continue;
   ctx.save();ctx.translate(px+(n*glyphAdvance+g.dx)*scale,py+g.dy*scale);ctx.rotate(g.rotate*Math.PI/180);ctx.scale(scale*g.scaleX,scale*g.scaleY);ctx.fillStyle=g.color||color;ctx.globalAlpha=g.opacity;ctx.fill(canvasPath(g.path));if(g.weight){ctx.strokeStyle=g.color||color;ctx.lineWidth=g.weight;ctx.stroke(canvasPath(g.path))}
   ctx.globalCompositeOperation='destination-out';ctx.globalAlpha=.65;ctx.fill(canvasPath(g.damage));ctx.restore();
   cursorX=px+(n+1)*glyphAdvance*scale;cursorY=py;
  }px+=word.width*scale;
 }
 if(reveal?.caret){ctx.save();ctx.fillStyle=color;ctx.globalAlpha=.7;ctx.fillRect(cursorX,cursorY,Math.max(1.2,scale*.48),size*.79);ctx.restore();}
 return py+size;
}
